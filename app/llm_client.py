PROMPTS = {"v1": SYSTEM_PROMPT_V1, "v2": SYSTEM_PROMPT_V2}



def chat(question: str, prompt_version: str = "v2", temperature: float = 0.0,
         timeout: int = 90, retries: int = 2) -> dict:
    """单轮问答。返回 {"success", "answer", "error"}，与 dify_client 保持同构。"""
    if not LLM_API_KEY:
        return {"success": False, "answer": "",
                "error": "未配置 LLM_API_KEY，请在 .env 中填写。"}

    headers = {
        "Authorization": f"Bearer {LLM_API_KEY}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": LLM_MODEL,
        "messages": [
            {"role": "system", "content": PROMPTS.get(prompt_version, SYSTEM_PROMPT_V2)},
            {"role": "user", "content": question},
        ],
        "temperature": temperature,
        "stream": False,
    }

    last_error = ""
    for attempt in range(retries + 1):
        try:
            resp = requests.post(f"{LLM_BASE_URL}/chat/completions",
                                 headers=headers, json=payload, timeout=timeout)
        except requests.exceptions.Timeout:
            last_error = "请求超时"
        except requests.exceptions.RequestException as exc:
            last_error = f"网络异常：{exc}"
        else:
            if resp.status_code == 200:
                try:
                    data = resp.json()
                    answer = data["choices"][0]["message"]["content"]
                except (ValueError, KeyError, IndexError):
                    return {"success": False, "answer": "",
                            "error": "返回结构不符合 OpenAI 兼容格式"}
                if not answer:
                    return {"success": False, "answer": "", "error": "返回内容为空"}
                return {"success": True, "answer": answer, "error": ""}

            body = resp.text[:200]
            last_error = f"HTTP {resp.status_code}：{body}"
            # 仅对限流与服务端错误重试；400/401 属于配置问题，重试无意义
            if resp.status_code not in (429, 500, 502, 503, 504):
                return {"success": False, "answer": "", "error": last_error}

        if attempt < retries:
            time.sleep(2 * (attempt + 1))

    return {"success": False, "answer": "", "error": last_error}
